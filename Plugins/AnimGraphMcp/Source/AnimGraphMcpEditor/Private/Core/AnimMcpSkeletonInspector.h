#pragma once

#include "CoreMinimal.h"
#include "Dom/JsonObject.h"
#include "Dom/JsonValue.h"

class USkeletalMesh;
class USkeleton;
struct FAutoCharacterizeResults;
struct FReferenceSkeleton;

/**
 * 스켈레톤 조회 (AI 애니 생성 Phase 1 — Docs/AIAnimation/ArchitectureAudit.md §8 · §10 inspect_skeleton).
 * 측정값만 담고 추정으로 채우지 않는다. 읽기 전용 — 템플릿 매칭은 트랜지언트 IK Rig 로 하고 저장하지 않는다.
 *
 * 엔진 경로 (5.7.4 소스):
 *   본·기준 포즈 — USkeleton 의 FReferenceSkeleton raw 배열(가상 본 제외, GetRawRefBoneInfo · GetRawRefBonePose). 컴포넌트 공간은 부모 순 누적.
 *   템플릿 매칭 — UIKRigController::AutoGenerateRetargetDefinition(FAutoCharacterizeResults) (IKRigController.cpp:493-502). 결과의 bUsedTemplate 가
 *                 거짓이면 ApplyAutoGeneratedRetargetDefinition 은 아무것도 하지 않고 false (:447-471) — 비표준 스켈레톤은 체인 0개.
 *                 템플릿 이름·매칭률은 이 C++ 경로로만 얻는다(Python 미노출, 감사 §2).
 *   참조 애셋 — AssetRegistry: 메시·시퀀스는 "Skeleton" 태그, IK Rig 는 "PreviewSkeletalMesh" 태그(AssetRegistrySearchable),
 *               리타기터는 그 IK Rig 패키지의 참조자.
 *   비교 — 이름이 같은 본끼리 기준 포즈 로컬 회전 각 차와 본 길이(부모까지 거리) 비. 이름이 다 같아도 포즈가 다르면 다른 리그다(감사 §8:
 *          UE4 마네킹은 68본 이름이 전부 Vesper 에 있지만 10~40° 다르다). same_rig = 회전 최대 < 1° ∧ 길이 비 0.99~1.01 — 참고 정보.
 */
namespace AnimMcpSkeletonInspector
{
	struct FInspectParams
	{
		USkeleton* Skeleton = nullptr;
		/** 템플릿 매칭·메시 소켓에 쓸 메시 (없으면 스켈레톤 프리뷰 메시, 그것도 없으면 레지스트리의 첫 메시) */
		USkeletalMesh* Mesh = nullptr;
		bool bDetails = false;
		USkeleton* CompareTo = nullptr;
	};

	TSharedRef<FJsonObject> Inspect(const FInspectParams& Params);

	/** [{name, parent}] (raw 본, 인덱스 순) — create_ik_rig 의 IKRIG_AUTO_FAILED details.bones[] 와 같은 모양 */
	TArray<TSharedPtr<FJsonValue>> DescribeBones(const FReferenceSkeleton& RefSkeleton, bool bDetails);

	/** 자동 캐릭터라이저를 메시에 돌린다 — 트랜지언트 IK Rig, 저장·트랜잭션 없음. 메시가 없으면 결과는 기본값(bUsedTemplate=false) */
	void Characterize(USkeletalMesh* Mesh, FAutoCharacterizeResults& OutResults);

	/** 캐릭터라이저 결과 → {used, name, percent, matching_bones, missing_bones, bones_with_missing_parent, pelvis, chains[], mesh} */
	TSharedRef<FJsonObject> TemplateMatchToJson(const FAutoCharacterizeResults& Results, const USkeletalMesh* Mesh);

	/** Characterize + TemplateMatchToJson (메시가 없으면 used=false, reason NO_MESH) */
	TSharedRef<FJsonObject> DescribeTemplateMatch(USkeletalMesh* Mesh);

	/** 기준 포즈 비교 {common, missing_in_other[], only_in_other_count, ref_rot_diff_deg{p50,max,max_bone}, bone_length_ratio{p50,min,max}, verdict} */
	TSharedRef<FJsonObject> Compare(const USkeleton* Skeleton, const USkeleton* Other);
}
