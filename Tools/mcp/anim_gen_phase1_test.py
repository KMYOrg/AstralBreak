def run_automation(filter_: str) -> dict:
    r = must(call("run_automation_tests", filter=filter_, timeout=120), f"run_automation_tests {filter_}")
    while not r.get("done"):
        time.sleep(3)
        r = must(call("poll_automation_tests", job_id=r["job_id"]), "poll")
    return r


def section_guard() -> None:
    print("== AnimGraphMcp.Generation.Guard")
    r = run_automation("AnimGraphMcp.Generation")
    for t in r["tests"]:
        print(f"   {t['name']}: {t['state']} errors={t.get('errors', [])[:3]} warnings={t.get('warnings', [])[:2]}")
    check(r["total"] >= 1 and r["failed"] == 0 and r["ok"], f"guard unit test passed ({r['passed']}/{r['total']})")


