def import_root() -> pathlib.Path:
    roots = must(call("get_editor_status"), "status")["generation"]["import_source_roots"]
    if not roots:
        print("[FAIL] no [AnimGraphMcp] ImportSourceRoots configured")
        sys.exit(1)
    return pathlib.Path(roots[0])


def ensure_fixture() -> pathlib.Path:
    path = import_root() / FIXTURE
    if not path.exists():
        out = subprocess.run([sys.executable, str(ROOT / "Tools" / "ue_exec.py"), str(ROOT / "Tools" / "scripts" / "anim_gen_export_fixture.py")],
                             cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
        print("   " + (out.stdout + out.stderr).strip().splitlines()[-1][:300])
    check(path.exists(), f"fixture FBX exists: {path.as_posix()}")
    return path


