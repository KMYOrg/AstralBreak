def run_scenario(**params) -> dict:
    job = must(call("run_anim_scenario", **params), "run_anim_scenario")
    while not job.get("done"):
        time.sleep(3)
        job = must(call("poll_automation_tests", job_id=job["job_id"]), "poll scenario")
    return job


def section_regression() -> None:
    print("== regression: Smoke · project automation · runtime scenarios")
    for filter_ in ("AnimGraphMcp.Smoke", "AstralBreak."):
        r = run_automation(filter_)
        bad = [t["name"] for t in r["tests"] if t["state"] != "passed"]
        print(f"   {filter_}: {r['passed']}/{r['total']} passed {bad}")
        check(r["total"] > 0 and r["failed"] == 0 and not bad, f"{filter_}* all passed ({r['passed']}/{r['total']})")
        STATE.setdefault("regression_tests", {})[filter_] = f"{r['passed']}/{r['total']}"
    idle = run_scenario(asset_path=RUNTIME_ABP, set_variables={"Speed": 0}, expect={"state_machines": {"Locomotion": "Idle"}})
    run = run_scenario(asset_path=RUNTIME_ABP, set_variables={"Speed": 300}, montage=RUNTIME_MONTAGE,
                       expect={"state_machines": {"Locomotion": "Run"}, "slots_active": ["UpperBody"]})
    for label, job in (("Speed 0 -> Idle", idle), ("Speed 300 -> Run + UpperBody", run)):
        t = job["tests"][0]
        check(t["state"] == "passed", f"runtime scenario {label} passed")
    STATE.setdefault("regression_tests", {})["runtime_scenarios"] = f"{sum(j['tests'][0]['state'] == 'passed' for j in (idle, run))}/2"


