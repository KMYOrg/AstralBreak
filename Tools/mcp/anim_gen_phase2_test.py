def run_automation(filter_: str) -> dict:
    r = must(call("run_automation_tests", filter=filter_, timeout=120), f"run_automation_tests {filter_}")
    while not r.get("done"):
        time.sleep(3)
        r = must(call("poll_automation_tests", job_id=r["job_id"]), "poll")
    return r


