def section_variant() -> None:
    print("== criterion 3 / test B: example D on Finisher1")
    windows = strike_windows(FINISHER1)
    print(f"   strike windows {windows}")
    if not check(len(windows) >= 2, "Finisher1 has at least two strikes"):
        return
    first, last = windows[0], windows[-1]
    src = numeric(FINISHER1)["numeric"]
    out = f"{RUN}/AS_Vesper_Sickle_Finisher1_FastSpin"
    # 마지막 타격을 먼저(원래 타임라인에서), 그다음 첫 타격 리타임 — 앞 구간이 짧아져도 앞 op 의 구간은 이미 적용됐다
    ops = [{"op": "rotate_root", "yaw": 180, "start": round(last[0] - 0.05, 3), "end": round(min(src["length"], last[1] + 0.05), 3)},
           {"op": "retime", "start": round(max(0.0, first[0] - 0.05), 3), "end": round(first[1] + 0.05, 3), "rate": 1.5}]
    r = must(apply(source=FINISHER1, asset_path=out, operations=ops, save=True), "apply example D")
    print(f"   {summarize(r)}")
    seg = r["planned"][1]["range"]["end"] - r["planned"][1]["range"]["start"]
    expected_len = src["length"] - seg + seg / 1.5
    builtin = r["validation"]["asset"]
    check(r["saved"] and builtin["status"] in ("PASSED", "PASSED_WITH_WARNINGS"),
          f"built-in validation {builtin['status']} (one-frame jumps judged against the source × max rate {r['validation']['inherited_max_deg_per_frame']}°)")
    # 요청 충족만 따로 — 재생 속도를 모르는 외부 호출은 1.5배로 빨라진 손 튐을 절대 규칙(90°)으로 보므로 구조 검사 + expect 만
    v = numeric(out, checks=["structural"], expect={"length": expected_len, "root_yaw_delta": src["root_yaw_delta_deg"] + 180, "loop": False},
                seams=[s["time"] for s in r["seams"]])
    print(f"   validate expect: {v['request']} status {v['status']}")
    check(v["status"] in ("PASSED", "PASSED_WITH_WARNINGS") and not v["request"]["issues"],
          f"validate_animation expect length {expected_len:.4f} (±1 frame) · root yaw +180 · no seam jump ({v['status']})")
    t_src, s_src, _ = profile(FINISHER1, ["hand_r"])
    t_out, s_out, _ = profile(out, ["hand_r"])
    peak_src = t_src[max(range(len(t_src)), key=lambda i: s_src["hand_r"][i] if t_src[i] <= first[1] + 0.1 else -1)]
    peak_out = t_out[max(range(len(t_out)), key=lambda i: s_out["hand_r"][i] if t_out[i] <= first[1] + 0.1 else -1)]
    check(peak_out < peak_src - 0.03, f"first strike peaks earlier ({peak_src:.3f}s -> {peak_out:.3f}s)")
    STATE["criterion_3"] = {"asset": out, "status": builtin["status"], "expect_status": v["status"], "windows": windows, "ops": ops, "length": [src["length"], r["length"]],
                            "root_yaw": v["request"]["root_yaw_delta_deg"], "first_peak": [peak_src, peak_out],
                            "inherited_max_deg_per_frame": r["validation"]["inherited_max_deg_per_frame"],
                            "issues": [s["code"] for s in r["validation"]["asset"]["structural"] if s["level"] != "info"]}


