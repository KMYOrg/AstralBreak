def retarget(rtg: str, assets: list[str], source_mesh: str, target_mesh: str, out: str, save: bool = False) -> dict:
    return must(call("retarget_animations", retargeter=rtg, assets=assets, source_mesh=source_mesh, target_mesh=target_mesh,
                     output_path=out, name_rule={"prefix": "AS_P2_"}, include_referenced=False, save=save), f"retarget {rtg}")


def ratios(validation: dict) -> list[dict]:
    rows = []
    for a in validation["assets"]:
        rel = a.get("relative", {})
        rows.append({"asset": a["asset"].rsplit(".", 1)[1], "status": a["status"],
                     **{k: rel.get(k) for k in ("ang_speed_p99_ratio", "common_bones_ang_speed_p99_ratio", "foot_planted_p50_ratio", "root_travel_ratio")},
                     "issues": [i["code"] for i in rel.get("issues", []) if i["level"] == "warning"]})
    return rows


