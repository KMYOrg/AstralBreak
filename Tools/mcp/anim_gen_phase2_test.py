def section_dirty() -> None:
    print("== dirty packages · source hashes (after)")
    allowed = must(call("get_editor_status"), "status")["generation"]["output_paths"]
    env = call("quit_editor")
    if env.get("ok"):
        print("[FAIL] quit_editor succeeded — the editor is shutting down (there were no dirty packages)")
        FAILS.append("quit_editor without flags quit the editor")
        return
    check(code(env) == "DIRTY_PACKAGES", "quit_editor without flags refuses with DIRTY_PACKAGES (editor keeps running)")
    dirty = [d["package"] for d in env["error"]["details"]["dirty_packages"]]
    outside = [p for p in dirty if not any((p + "/").startswith(a) for a in allowed)]
    print(f"   {len(dirty)} dirty package(s), outside GenerationOutputPaths: {outside}")
    check(not outside, "no dirty package outside GenerationOutputPaths")
    source_dirty = [p for p in dirty if p in SOURCES]
    check(not source_dirty, "no source package is dirty")
    if "source_hashes" in STATE:
        changed = [p for p, h in STATE["source_hashes"].items() if sha256(p) != h]
        check(not changed, f"source .uasset SHA-256 unchanged ({len(STATE['source_hashes'])} files)")
    STATE["dirty_at_end"] = {"count": len(dirty), "outside": outside}


