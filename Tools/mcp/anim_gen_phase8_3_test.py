def section_timing() -> None:
    print("== fix.timing on the existing assets")
    for key, (asset, _, _, family) in TARGETS.items():
        job = run_job(request(f"{camel(key)}Timed", family, reference_animations=[asset], provider="existing_motion", duration_seconds=4.0,
                              fix={"timing": True}), f"{key} timing")
        tm = job.get("timing") or {}
        if not tm:
            continue
        b, a = tm["before"], tm["after"]
        planned = job["_plan"]["candidates"][0]["steps"][1].get("resolved") or {}
        ratio = a["peak_cm_s"] / b["peak_cm_s"] if b["peak_cm_s"] else 0
        check(planned.get("ops") == tm["ops"], f"{key}: ops shown at plan = ops run")
        check([o["op"] for o in tm["ops"]] in (["trim", "time_warp"], ["time_warp"]), f"{key}: ops {[o['op'] for o in tm['ops']]} (one trim + one time_warp)")
        check(tm["rate"] * 0.75 <= ratio <= tm["rate"] * 1.1,
              f"{key}: peak {b['peak_cm_s']} → {a['peak_cm_s']} cm/s (×{ratio:.3f} vs planned core ×{tm['rate']} — ≥ ×0.75 with antialias {tm['antialias']})")
        # 속도 단차 — 출력 프레임 사이 배율 변화 ≤ 배율 곡선의 가장 가파른 램프(매듭 사이 |Δ배율| / 출력 프레임) + 0.05
        sim = timing.simulate(tm["ops"], b["length"], FPS)
        step = timing.max_rate_step(sim["source_times"], FPS)
        ramp = max(abs(r1 - r0) / max((n1 - n0) * FPS, 1.0) for (_, n0, r0), (_, n1, r1) in zip(tm["warp"], tm["warp"][1:]))
        check(step <= ramp + 0.05, f"{key}: rate change per frame {step:.3f} ≤ steepest ramp {ramp:.3f} + 0.05 (no speed steps)")
        check(a["tail_still_s"] <= 0.3 + 1 / 30 + 1e-6, f"{key}: still tail {b['tail_still_s']} → {a['tail_still_s']} s")
        warns = warnings_of(job)
        check("SEAM_JUMP" not in warns and job["validation"]["status"] != "FAILED", f"{key}: validation {job['validation']['status']} {warns}")
        _, pa, _ = profile(asset)
        _, pb, _ = profile(job["generated_assets"][0])
        boxes = {bn: round(max(abs(x - y) for x, y in zip(box(pa[bn]), box(pb[bn]))), 2) for bn in ("hand_l", "hand_r", "foot_l", "foot_r")}
