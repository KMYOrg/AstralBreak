def sha256(path: str) -> str:
    return hashlib.sha256((ROOT / "Content" / (path.removeprefix("/Game/") + ".uasset")).read_bytes()).hexdigest()


def content_changes() -> list[str]:
    out = subprocess.run(["git", "status", "--porcelain", "--untracked-files=all", "--", "Content"], cwd=ROOT, capture_output=True,
                         text=True, encoding="utf-8").stdout
    return sorted(line[3:].strip().strip('"') for line in out.splitlines() if line.strip())


def profile(asset: str) -> tuple[list[float], dict, dict]:
    item = must(editor("validate_animation", assets=[asset], skeleton=VESPER, profile_bones=PROFILE_BONES, profile_positions=True), f"profile {asset}")["assets"][0]
    num = item["numeric"]
    return num["profile"]["times"], num["profile"]["position_cm"], num


def track_diff(a: dict, b: dict, bones: list[str]) -> dict:
    return {bn: round(max(mm._dist(x, y) for x, y in zip(a[bn], b[bn])), 3) for bn in bones if a.get(bn) and b.get(bn)}


def box(track: list) -> list[float]:
    return [max(p[i] for p in track) - min(p[i] for p in track) for i in range(3)]


