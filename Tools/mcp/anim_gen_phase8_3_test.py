def finish() -> int:
    out = ROOT / "Tools" / "mcp" / "anim_gen_phase8_3_state.json"
    # 섹션 단위로 갱신 — 앞 실행의 다른 섹션(대상별 timing · legs …)은 남긴다. 이번 실행의 run · out 은 runs[] 에도 남는다
    merged = json.loads(out.read_text(encoding="utf-8")) if out.is_file() else {}
    targets = merged.get("targets") or {}
    for key, value in STATE["targets"].items():
        targets[key] = {**(targets.get(key) or {}), **value}
    runs = (merged.get("runs") or []) + [{"run": RUN, "out": OUT.as_posix(), "sections": STATE.get("sections")}]
    merged.update({k: v for k, v in STATE.items() if k not in ("targets", "run", "out", "state_dir")})
    merged.update(targets=targets, runs=runs)
    merged.setdefault("run", RUN)
    out.write_text(json.dumps(merged, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"state -> {out.as_posix()}")
    print(f"\n{len(FAILS)} failure(s)")
    for f in FAILS:
        print("  - " + f)
    print("PASS" if not FAILS else "FAIL")
    return 0 if not FAILS else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default=",".join(SECTIONS), help="comma separated: " + ",".join(SECTIONS))
    args = ap.parse_args()
    t0 = time.time()
    STATE["sections"] = [s.strip() for s in args.only.split(",")]
    for name in args.only.split(","):
        SECTIONS[name.strip()]()
    STATE["seconds"] = round(time.time() - t0, 1)
    return finish()


