        codes = [lm["code"] for lm in job["limitations"]]
        check("TIMING_CHANGED_LENGTH" in codes and "DURATION_MISMATCH" not in codes, f"{key}: limitations {codes}")
        STATE["targets"].setdefault(key, {})["timing"] = {"asset": job["generated_assets"][0], "job": job["job_id"], "rate": tm["rate"],
                                                          "recovery_rate": tm["recovery_rate"], "antialias": tm["antialias"], "windows": tm["windows"],
                                                          "cut": tm["cut"], "profile": tm["profile"], "ops": tm["ops"], "warp": tm["warp"], "before": b,
                                                          "after": a, "peak_ratio": round(ratio, 3), "rate_step": round(step, 3), "boxes": boxes, "warnings": warns}


