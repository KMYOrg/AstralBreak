        worse = [s for s in ("l", "r") if (tgt["slide_p95"][s] or 0) > (before["slide_p95"][s] or 0) + 0.05]
        check(not worse, f"{key}: Vesper planted slide p95 {before['slide_p95']} → {tgt['slide_p95']} cm/s")
        check(abs(src["after"]["ratio"]["planted_max"] - tgt["ratio"]["planted_max"]) <= 0.1,
              f"{key}: model prediction {src['after']['ratio']['planted_max']} ≈ Vesper {tgt['ratio']['planted_max']}")
        _, pa, _ = profile(asset)
        _, pb, _ = profile(new)
        # 상체는 골반과 함께 오른다(keep_knee_bend) — 손목 · 머리의 골반 기준 위치와 골반 수평은 그대로, 골반 높이 차 = 계획한 상승
        rel = lambda p, bn: [[x[i] - y[i] for i in range(3)] for x, y in zip(p[bn], p["pelvis"])]  # noqa: E731
        upper = {bn: round(max(mm._dist(x, y) for x, y in zip(rel(pa, bn), rel(pb, bn))), 3) for bn in ("hand_l", "hand_r", "head")}
        horizontal = round(max(((x[0] - y[0]) ** 2 + (x[1] - y[1]) ** 2) ** 0.5 for x, y in zip(pa["pelvis"], pb["pelvis"])), 3)
        rise = [y[2] - x[2] for x, y in zip(pa["pelvis"], pb["pelvis"])]
        rise_stat = {"p50": round(mm.percentile(rise, 0.5), 2), "max": round(max(rise), 2)}
        check(max(upper.values()) <= TRACK_TOL_CM and horizontal <= TRACK_TOL_CM,
              f"{key}: upper body relative to the pelvis {upper} · pelvis horizontal {horizontal} cm unchanged")
        pr = src.get("pelvis_raise") or {}
        planned = pr.get("space_cm") or {"p50": 0.0, "max": 0.0}
        check(pr.get("applied") and abs(rise_stat["p50"] - planned["p50"]) <= 0.5 and abs(rise_stat["max"] - planned["max"]) <= 0.5,
              f"{key}: pelvis raised p50 {rise_stat['p50']} · max {rise_stat['max']} cm (planned {planned['p50']} · {planned['max']}, bone {pr.get('bone')})")
        kb_before, kb_after = before.get("knee_bend") or {}, tgt.get("knee_bend") or {}
        check(all(kb_after.get(s) and kb_after[s]["p50"] <= kb_before[s]["p50"] + KNEE_MARGIN_DEG for s in ("l", "r")),
              f"{key}: Vesper knee bend p50 L/R {kb_before.get('l', {}).get('p50')}/{kb_before.get('r', {}).get('p50')} → "
              f"{kb_after.get('l', {}).get('p50')}/{kb_after.get('r', {}).get('p50')}° (≤ before + {KNEE_MARGIN_DEG:g})")
        warns = warnings_of(job)
        check(job["validation"]["status"] != "FAILED", f"{key}: validation {job['validation']['status']} {warns}")
        keys = ("ratio", "slide_p95", "contact_pct", "knee_gap_min_cm", "knee_bend")
        STATE["targets"].setdefault(key, {})["legs"] = {
            "asset": new, "job": job["job_id"], "vesper_before": {k: before.get(k) for k in keys}, "vesper_after": {k: tgt.get(k) for k in keys},
            "predicted_before": src["before"], "predicted_after": src["after"], "source_before": src["source_before"], "source_after": src["source_after"],
            "stance": src["stance"], "ik": src["ik"], "scale": src["scale"], "pelvis_raise": pr, "pelvis_rise_vesper_cm": rise_stat,
            "pelvis_horizontal_cm": horizontal, "upper_rel_pelvis_cm": upper, "warnings": warns}


