def quality(asset: str, bones: dict) -> dict:
    """8-3 후속 탐침과 같은 측정 — 떨림(zigzag 최대, 골반 제외 측정 본) · 손목 굽힘(팔꿈치 · 손목 · 중지 첫 마디) · 무릎 굽힘(넓적다리 · 종아리 · 발) ·
    관통(body_clearance) · 손-머리 · 꼬임(candidate_metrics)."""
    names = sorted(set(RetargetPipe.profile_bones(bones)) | set(QUALITY_EXTRA))
    item = must(editor("validate_animation", assets=[asset], skeleton=VESPER, profile_bones=names, profile_positions=True,
                       body_clearance={"mesh": MESH, "ik_rig": IK_TARGET}), f"quality {asset}")["assets"][0]
    num = item["numeric"]
    pos, times = num["profile"]["position_cm"], num["profile"]["times"]
    scale = (num.get("pelvis_height_cm") or 100.0) / 100.0
    m = RetargetPipe.candidate_metrics(item, bones, None, None)
    tracks = [t for bn, t in pos.items() if t and bn != "pelvis"]
    clear = m.get("clearance") or {}
    return {"asset": asset, "length": num.get("length"), "zigzag": mm.zigzag(tracks, times, scale)["max"], "deg_per_frame": num.get("max_deg_per_frame"),
            "wrist_bend": {s: mm.wrist_bend(pos[bones[f"elbow_{s}"]], pos[bones[f"hand_{s}"]], pos[f"middle_01_{s}"]) for s in ("l", "r")},
            "knee_bend": {s: mm.knee_bend(pos[f"thigh_{s}"], pos[f"calf_{s}"], pos[f"foot_{s}"]) for s in ("l", "r")},
            "clearance": {"penetration_pct": clear.get("penetration_pct"), "depth_max": clear.get("depth_max")},
            "head_min_cm": (m.get("head") or {}).get("min_cm"),
            "cross": {"crossed_pct": (m.get("cross") or {}).get("crossed_pct"), "depth_max_cm": ((m.get("cross") or {}).get("depth_cm") or {}).get("max")},
            "_tracks": tracks, "_times": times, "_scale": scale}


def not_worse(key: str, name: str, q: dict, o: dict) -> list[str]:
    """원본 대비 나빠진 항목 — 관통 깊이 +0.5 cm · 관통 % +2%p(다리만 — 시간은 머리 · 꼬리를 잘라 분모가 다르다) · 손목 굽힘 p95 +3° · 최대 +5° ·
    손-머리 최소 −1 cm · 꼬임 % +2%p(다리만) · 꼬임 깊이 +1 cm."""
    bad = []
    num = lambda v: v if v is not None else 0.0  # noqa: E731
    if num(q["clearance"]["depth_max"]) > num(o["clearance"]["depth_max"]) + 0.5:
        bad.append(f"penetration depth {o['clearance']['depth_max']} → {q['clearance']['depth_max']}")
    if name == "legs" and num(q["clearance"]["penetration_pct"]) > num(o["clearance"]["penetration_pct"]) + 2.0:
        bad.append(f"penetration % {o['clearance']['penetration_pct']} → {q['clearance']['penetration_pct']}")
    for s in ("l", "r"):
        if num(q["wrist_bend"][s]["p95"]) > num(o["wrist_bend"][s]["p95"]) + 3.0 or num(q["wrist_bend"][s]["max"]) > num(o["wrist_bend"][s]["max"]) + 5.0:
            bad.append(f"wrist {s} p95/max {o['wrist_bend'][s]['p95']}/{o['wrist_bend'][s]['max']} → {q['wrist_bend'][s]['p95']}/{q['wrist_bend'][s]['max']}")
    if o["head_min_cm"] is not None and num(q["head_min_cm"]) < o["head_min_cm"] - 1.0:
        bad.append(f"hand-head min {o['head_min_cm']} → {q['head_min_cm']} cm")
    if name == "legs" and num(q["cross"]["crossed_pct"]) > num(o["cross"]["crossed_pct"]) + 2.0:
        bad.append(f"crossed % {o['cross']['crossed_pct']} → {q['cross']['crossed_pct']}")
    if num(q["cross"]["depth_max_cm"]) > num(o["cross"]["depth_max_cm"]) + 1.0:
        bad.append(f"cross depth max {o['cross']['depth_max_cm']} → {q['cross']['depth_max_cm']}")
    return bad


def section_quality() -> None:
    print("== quality: original · legs · timed · combined — jitter · knee bend · penetration · wrist · hand-head · crossing")
    saved = ROOT / "Tools" / "mcp" / "anim_gen_phase8_3_state.json"
    previous = json.loads(saved.read_text(encoding="utf-8")).get("targets", {}) if saved.is_file() else {}
    bones = RetargetPipe.selection_bones(EDITOR, VESPER, [], "quality")
    strip = lambda q: {k: v for k, v in q.items() if not k.startswith("_")}  # noqa: E731
    for key, (asset, _, _, _) in TARGETS.items():
        st = {**(previous.get(key) or {}), **(STATE["targets"].get(key) or {})}
        variants = {"legs": ((st.get("legs") or {}).get("asset"), 1.0), "timed": ((st.get("timing") or {}).get("asset"), (st.get("timing") or {}).get("rate")),
                    "fixed": ((st.get("combined") or {}).get("asset"), ((st.get("combined") or {}).get("timing") or {}).get("rate"))}
        o = quality(asset, bones)
        rows = {"orig": strip(o)}
        measured = {}
        for name, (path, rate) in variants.items():
            if not path:
                check(False, f"{key}: no {name} asset (run --only {'legs' if name == 'legs' else 'timing' if name == 'timed' else 'combined'} first)")
                continue
            q = quality(path, bones)
            row = strip(q)
            if name == "legs":
                limit = o["zigzag"] + ZIGZAG_LEGS_MARGIN
                check(q["zigzag"] <= limit, f"{key} {name}: jitter {o['zigzag']} → {q['zigzag']} (≤ original + {ZIGZAG_LEGS_MARGIN:g})")
            else:
                uniform = mm.zigzag_at_rate(o["_tracks"], o["_times"], rate, o["_scale"])
                row["uniform_reference"] = uniform
                check(q["zigzag"] <= ZIGZAG_UNIFORM_SHARE * uniform and q["zigzag"] < PREVIOUS_ZIGZAG[key][name],
                      f"{key} {name}: jitter {o['zigzag']} → {q['zigzag']} (≤ uniform ×{rate} reference {uniform} × {ZIGZAG_UNIFORM_SHARE:g} = "
                      f"{round(ZIGZAG_UNIFORM_SHARE * uniform, 2)} · first version {PREVIOUS_ZIGZAG[key][name]}; original × r² {round(o['zigzag'] * rate * rate, 2)})")
            if name in ("legs", "fixed"):
                # 합본은 같은 시간 보정의 원본(시간만)과 — 시간 보정은 자세를 바꾸지 않고 머리 · 꼬리를 잘라 p50 의 모집단만 바꾼다
                base, base_name = (measured["timed"], "timed original") if name == "fixed" and "timed" in measured else (o, "original")
                check(all(q["knee_bend"][s]["p50"] <= base["knee_bend"][s]["p50"] + KNEE_MARGIN_DEG for s in ("l", "r")),
                      f"{key} {name}: knee bend p50 L/R {base['knee_bend']['l']['p50']}/{base['knee_bend']['r']['p50']} → "
                      f"{q['knee_bend']['l']['p50']}/{q['knee_bend']['r']['p50']}° (≤ {base_name} + {KNEE_MARGIN_DEG:g})")
            bad = not_worse(key, name, q, o)
            check(not bad, f"{key} {name}: not worse than the original (penetration · wrist · hand-head · crossing){' — ' + '; '.join(bad) if bad else ''}")
            rows[name] = row
            measured[name] = q
        STATE["targets"].setdefault(key, {})["quality"] = rows


def capture(out: pathlib.Path, asset: str, label: str, **params) -> dict:
    env = editor("capture_animation", asset=asset, mesh=MESH, facing="+Y", output_dir=out.as_posix(), label=label, **params)
    res = must(env, f"capture {asset}")
    seq = res.get("sequence") or {}
    if seq.get("frames"):
        res["animation"] = apng.assemble(seq["frames"], out / "animation.png", float(seq["fps"]))
    return res


