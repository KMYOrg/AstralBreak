    deepest = lambda keys, frames: max((d for k in keys for f in frames for d in [series[k][f]] if d is not None), default=None)  # noqa: E731
    hand_head = deepest([(s, "hand", "head_neck") for s in "lr"], win(USER_SPOTS["hand_head_s"]))
