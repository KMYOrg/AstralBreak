def detect_events(prof: dict, num: dict, b: dict) -> dict:
    """timing 신호(손목 속도 — select · fix.timing 과 같은 원천)로 swing_peak · swing [시작, 끝], 발목 접지(detect_contacts)로 두 발 디딘 구간."""
