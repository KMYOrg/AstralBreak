def strip_seconds(obj):
    """비교용 — seconds(측정 시간)를 뺀 사본."""
    if isinstance(obj, dict):
        return {k: strip_seconds(v) for k, v in obj.items() if k != "seconds"}
    if isinstance(obj, list):
        return [strip_seconds(v) for v in obj]
    return obj


