"""C++ 코드 생성 — 바인딩 계약 · 생성 베이스/스텁 렌더 · 생성 파일 읽기 (설계 §3-3).

결정적이다: 같은 계약이면 같은 바이트. 계약 문서에는 생성기 식별자(템플릿 4개 + setter 조각의 해시)가 들어 있어
템플릿이 바뀌어도 해시가 바뀐다 — 계약 해시가 생성 결과의 정체성이다.

계약 = 바인딩 위젯마다 {name, widget_class, data, kind, format?, optional, setter}. 바인딩은 추가만 된다:
  - spec 에 새로 생긴 이름 → 추가
  - 이전 계약에 있고 spec 에서 빠진 이름 → optional(BindWidgetOptional)로 남김 — 이전 run 의 WBP 가 계속 컴파일되게
  - 같은 이름의 위젯 클래스가 바뀜 → 거부(BINDING_RETYPE) — 옛 WBP 는 이름으로 묶여 있어 타입이 바뀌면 깨진다
  - data · kind · format 이 바뀜 → 허용(setter 가 바뀐다). 스텁이 옛 setter 를 부르면 빌드가 실패하고 codegen 이 원복한다
setter 는 data id 가 정체성이다: spec 바인딩이 차지한 data 의 setter 는 그 바인딩 것이고, 같은 data 를 쓰던 빠진 바인딩은 setter 를 잃는다
(위젯 이름을 바꿔도 사람 코드가 부르는 SetX 는 그대로 새 위젯을 움직인다).
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import re
import string

from core import spec as spec_mod
from core.config import UIGEN_DIR

TEMPLATE_DIR = UIGEN_DIR / "codegen"
TEMPLATES = {"view_base_h": "view_base.h.tmpl", "view_base_cpp": "view_base.cpp.tmpl",
             "widget_h": "widget.h.tmpl", "widget_cpp": "widget.cpp.tmpl"}
CODEGEN_VERSION = 1

MARKER = "// AUTO-GENERATED by uigen"
HASH_PREFIX = "// uigen-contract-hash: "
CONTRACT_PREFIX = "// uigen-contract: "
BANNER_FIRST = (MARKER + " — 손대지 말 것: 계약이 바뀌면 다음 codegen 이 덮어쓴다. "
                "이 첫 줄을 지우면 사람 소유가 되고 uigen 은 쓰기를 거부한다.")

IDENT = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")

# spec 위젯 타입 = UMG 클래스 이름(U 접두 없이) — list_bind_widgets 의 widget_class 와 같은 표기
WIDGET_INCLUDE = {t: f"Components/{t}.h" for t in spec_mod.WIDGET_TYPES}

# flag 로 보일 때의 가시성 — HUD 요소는 입력을 받지 않는다(버튼만 Visible)
FLAG_SHOWN = {"Button": "Visible"}
FLAG_SHOWN_DEFAULT = "SelfHitTestInvisible"

# setter 조각 (설계 §3-3 표). ${name} = 바인딩 위젯, ${data} = data id
SETTERS = {
    "progress": {"param": "float Percent",
                 "doc": "${data} (progress) → ${name} 의 채움 비율(0 ~ 1 로 자른다).",
                 "body": ["${name}->SetPercent(FMath::Clamp(Percent, 0.0f, 1.0f));"]},
    "text": {"param": "const FText& InText",
             "doc": "${data} (text) → ${name} 의 글자.",
             "body": ["${name}->SetText(InText);"]},
    "number_int": {"param": "int32 Value",
                   "doc": "${data} (number, 형식 \"${format}\") → ${name} 의 글자(자릿수 묶음 없음).",
                   "body": ["FNumberFormattingOptions Options;",
                            "Options.SetUseGrouping(false);",
                            "${name}->SetText(FText::AsNumber(Value, &Options));"]},
    "number_float": {"param": "float Value",
                     "doc": "${data} (number, 형식 \"${format}\") → ${name} 의 글자(소수 ${digits} 자리 · 자릿수 묶음 없음).",
                     "body": ["FNumberFormattingOptions Options;",
                              "Options.SetUseGrouping(false).SetMinimumFractionalDigits(${digits}).SetMaximumFractionalDigits(${digits});",
                              "${name}->SetText(FText::AsNumber(Value, &Options));"]},
    "flag": {"param": "bool bVisible",
             "doc": "${data} (flag) → ${name} 보이기(${shown}) / 접기(Collapsed).",
             "body": ["${name}->SetVisibility(bVisible ? ESlateVisibility::${shown} : ESlateVisibility::Collapsed);"]},
    "image": {"param": "UTexture2D* Texture",
              "doc": "${data} (image) → ${name} 의 브러시 텍스처(브러시 크기는 그대로).",
              "body": ["${name}->SetBrushFromTexture(Texture, false);"]},
}


class ContractError(ValueError):
    def __init__(self, code: str, message: str, **details):
        self.code = code
        self.details = details
        super().__init__(f"{code}: {message}")


# ---------------------------------------------------------------------------------------------------------------------
# 이름

def pascal(data_id: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in data_id.split("_") if p)


def setter_name(entry: dict) -> str:
    base = "Set" + pascal(entry["data"])
    return base + "Visible" if entry["kind"] == "flag" else base


def fraction_digits(fmt: str | None) -> int:
    return len(fmt.split(".", 1)[1]) if fmt and "." in fmt else 0


def setter_kind(entry: dict) -> str:
    if entry["kind"] == "number":
        return "number_float" if fraction_digits(entry.get("format")) else "number_int"
    return entry["kind"]


