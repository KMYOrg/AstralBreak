# 계약

def binding_entries(spec: dict) -> list[dict]:
    """spec 의 바인딩 → 계약 항목(이름순). setter 는 merge 가 채운다."""
    index = spec_mod.widget_index(spec)
    out = []
    for wid, b in spec_mod.bound_widgets(spec).items():
        e = {"name": wid, "widget_class": index[wid]["type"], "data": b["data"], "kind": b["kind"],
             "optional": bool(b.get("optional", False))}
        if b["kind"] == "number":
            e["format"] = b.get("format") or "0"
        out.append(e)
    return sorted(out, key=lambda e: e["name"])


def _signature(e: dict) -> tuple:
    return e["data"], e["kind"], e.get("format")


def merge(new: list[dict], previous: list[dict] | None) -> tuple[list[dict], dict]:
    """이번 spec 의 바인딩 + 이전 계약 → (합친 계약 항목, 바뀐 것). 바인딩은 추가만(모듈 설명)."""
    prev = {b["name"]: b for b in (previous or [])}
    changes: dict[str, list[str]] = {"added": [], "demoted": [], "changed": [], "restored": []}
    merged: dict[str, dict] = {}
    for e in new:
        p = prev.get(e["name"])
        if p is None:
            changes["added"].append(e["name"])
        else:
            if p["widget_class"] != e["widget_class"]:
                raise ContractError("BINDING_RETYPE",
                                    f"'{e['name']}' is bound as {p['widget_class']} in the existing contract and is {e['widget_class']} in the spec — "
                                    "a bound widget keeps its class (older WBPs bind it by name); use a new widget name",
                                    widget=e["name"], was=p["widget_class"], now=e["widget_class"])
            if _signature(p) != _signature(e):
                changes["changed"].append(e["name"])
            if p["optional"] and not e["optional"]:
                changes["restored"].append(e["name"])
            if not p["optional"] and e["optional"]:
                changes["demoted"].append(e["name"])
        merged[e["name"]] = {**e, "setter": setter_name(e)}
    claimed = {e["data"] for e in new}
    for name, p in prev.items():
        if name in merged:
            continue
        if not p["optional"]:
            changes["demoted"].append(name)
        setter = None if p["data"] in claimed else p.get("setter")
        merged[name] = {**p, "optional": True, "setter": setter}
    out = [merged[k] for k in sorted(merged)]
    seen: dict[str, str] = {}
    for e in out:
        s = e["setter"]
        if s is None:
            continue
        if s in seen:
            raise ContractError("SETTER_COLLISION", f"'{seen[s]}' and '{e['name']}' both need {s}() — rename a binding data id",
                                setter=s, widgets=[seen[s], e["name"]])
        seen[s] = e["name"]
    clash = sorted(set(seen) & {e["name"] for e in out})
    if clash:
        raise ContractError("NAME_COLLISION", f"widget name(s) {clash} collide with generated setter names", names=clash)
    return out, {k: sorted(v) for k, v in changes.items()}


def _template_text(key: str) -> str:
    return (TEMPLATE_DIR / TEMPLATES[key]).read_text(encoding="utf-8").replace("\r\n", "\n")


def generator_id() -> str:
    """생성기 식별자 — 버전 + 템플릿 · setter 조각의 해시. 바뀌면 계약 해시도 바뀌어 다시 생성된다."""
    h = hashlib.sha1()
    h.update(str(CODEGEN_VERSION).encode())
    for key in sorted(TEMPLATES):
        h.update(key.encode() + b"\0" + _template_text(key).encode("utf-8") + b"\0")
    h.update(json.dumps(SETTERS, sort_keys=True, ensure_ascii=False).encode("utf-8"))
    return f"{CODEGEN_VERSION}:{h.hexdigest()[:12]}"


def contract_doc(screen_id: str, screen: dict, codegen_cfg: dict, bindings: list[dict]) -> dict:
    return {"schema_version": 1, "generator": generator_id(), "module": codegen_cfg["module"], "api": codegen_cfg["api_macro"],
            "ui_dir": codegen_cfg["ui_dir"], "screen": screen_id, "feature": screen["feature"], "view_base": screen["view_base"],
            "widget": screen["widget"], "bindings": bindings}


def contract_hash(doc: dict) -> str:
    return "sha1:" + hashlib.sha1(spec_mod.canonical_json(doc).encode("utf-8")).hexdigest()


def contract_diff(bindings: list[dict], live: list[dict]) -> list[str]:
    """계약과 클래스 리플렉션(list_bind_widgets)의 차이 — 이름 · 위젯 클래스 · 선택 여부."""
    want = {b["name"]: (b["widget_class"], bool(b["optional"])) for b in bindings}
    have = {b["name"]: (b.get("widget_class"), bool(b.get("optional"))) for b in live}
    out = []
    for name in sorted(set(want) | set(have)):
        if name not in have:
            out.append(f"{name}: missing in the class (want {want[name][0]}{' optional' if want[name][1] else ''})")
        elif name not in want:
            out.append(f"{name}: in the class but not in the contract ({have[name][0]})")
        elif want[name] != have[name]:
            out.append(f"{name}: class has {have[name][0]}{' optional' if have[name][1] else ''}, "
                       f"contract wants {want[name][0]}{' optional' if want[name][1] else ''}")
    return out


