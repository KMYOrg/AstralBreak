# 렌더

def _sub(text: str, **values) -> str:
    return string.Template(text).substitute(**{k: str(v) for k, v in values.items()})


def _setter_values(doc: dict, e: dict) -> dict:
    return {"name": e["name"], "data": e["data"], "format": e.get("format", ""), "digits": fraction_digits(e.get("format")),
            "shown": FLAG_SHOWN.get(e["widget_class"], FLAG_SHOWN_DEFAULT)}


def render(doc: dict, chash: str) -> dict[str, str]:
    """계약 → 파일 4개의 텍스트(LF). 쓰기 때 CRLF 로 바꾼다."""
    vb, screen = doc["view_base"], doc["screen"]
    with_setter = [e for e in doc["bindings"] if e.get("setter")]
    classes = sorted({e["widget_class"] for e in doc["bindings"]})
    needs_texture = any(setter_kind(e) == "image" for e in with_setter)

    forward = [f"class U{c};" for c in classes] + (["class UTexture2D;"] if needs_texture else [])
    decls, defs = [], []
    for e in with_setter:
        sk = SETTERS[setter_kind(e)]
        vals = _setter_values(doc, e)
        decls.append(f"\t/** {_sub(sk['doc'], **vals)} */\n"
                     f"\tUFUNCTION(BlueprintCallable, Category = \"uigen|{screen}\")\n"
                     f"\tvoid {e['setter']}({sk['param']});\n")
        body = "".join(f"\t\t{_sub(line, **vals)}\n" for line in sk["body"])
        defs.append(f"void U{vb}::{e['setter']}({sk['param']})\n{{\n\tif ({e['name']})\n\t{{\n{body}\t}}\n}}\n")
    props = []
    for e in doc["bindings"]:
        kind = e["kind"] + (f" \"{e['format']}\"" if e.get("format") else "")
        note = " · 선택(BindWidgetOptional)" if e["optional"] else ""
        setter = f" · {e['setter']}()" if e.get("setter") else " · setter 없음(같은 data 를 다른 바인딩이 씀)"
        props.append(f"\t/** {e['data']} · {kind}{note}{setter} */\n"
                     f"\tUPROPERTY(meta = ({'BindWidgetOptional' if e['optional'] else 'BindWidget'}))\n"
                     f"\tTObjectPtr<U{e['widget_class']}> {e['name']};\n")
    includes = [f'#include "{WIDGET_INCLUDE[c]}"' for c in classes] + (['#include "Engine/Texture2D.h"'] if needs_texture else [])

    contract_line = CONTRACT_PREFIX + json.dumps(doc, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    banner_h = "\n".join([BANNER_FIRST, HASH_PREFIX + chash, contract_line]) + "\n"
    banner_cpp = "\n".join([BANNER_FIRST, HASH_PREFIX + chash]) + "\n"
    common = {"view_base": vb, "widget": doc["widget"], "screen": screen, "api": doc["api"], "feature": doc["feature"], "ui_dir": doc["ui_dir"]}
    return {
        "view_base_h": _sub(_template_text("view_base_h"), banner=banner_h, forward_decls="".join(f"{x}\n" for x in forward),
                            setter_decls="\n".join(decls), properties="\n".join(props), **common),
        "view_base_cpp": _sub(_template_text("view_base_cpp"), banner=banner_cpp, includes="".join(f"{x}\n" for x in includes),
                              setter_defs="\n".join(defs), **common),
        "widget_h": _sub(_template_text("widget_h"), **common),
        "widget_cpp": _sub(_template_text("widget_cpp"), **common),
    }
