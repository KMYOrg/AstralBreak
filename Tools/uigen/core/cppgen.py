# 생성 파일 읽기

def read_generated(path: pathlib.Path) -> dict:
    """{exists, owned, hash, contract, corrupt} — owned = 첫 줄이 표식. 사람이 표식을 지우면 owned=false(사람 소유)."""
    out = {"exists": False, "owned": False, "hash": None, "contract": None, "corrupt": None}
    path = pathlib.Path(path)
    if not path.is_file():
        return out
    out["exists"] = True
    lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()[:8]
    out["owned"] = bool(lines) and lines[0].startswith(MARKER)
    if not out["owned"]:
        return out
    for ln in lines[1:]:
        if ln.startswith(HASH_PREFIX):
            out["hash"] = ln[len(HASH_PREFIX):].strip()
        elif ln.startswith(CONTRACT_PREFIX):
            try:
                out["contract"] = json.loads(ln[len(CONTRACT_PREFIX):])
            except ValueError as exc:
                out["corrupt"] = f"contract line is not JSON: {exc}"
    if out["hash"] is None:
        out["corrupt"] = out["corrupt"] or "no contract hash line"
    elif out["contract"] is not None and contract_hash(out["contract"]) != out["hash"]:
        out["corrupt"] = "contract line does not match its hash line (edited by hand?)"
    return out


