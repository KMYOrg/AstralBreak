# 경로 · 화면 설정

def validate_screen(screen_id: str, screen: dict) -> list[str]:
    errs = []
    for key in ("feature", "view_base", "widget"):
        v = screen.get(key)
        if not isinstance(v, str) or not IDENT.match(v):
            errs.append(f"screens.yaml {screen_id}.{key} '{v}' is not an identifier")
    if not errs:
        if not screen["view_base"].endswith("ViewBase"):
            errs.append(f"screens.yaml {screen_id}.view_base '{screen['view_base']}' must end with ViewBase (header names are unique per module — §3-3 rule 5)")
        if not screen["widget"].endswith("Widget"):
            errs.append(f"screens.yaml {screen_id}.widget '{screen['widget']}' must end with Widget (§3-3 rule 5)")
    return errs


def target_paths(module_root: pathlib.Path, ui_dir: str, screen: dict) -> dict[str, pathlib.Path]:
    feature_dir = pathlib.Path(module_root) / ui_dir / screen["feature"]
    auto = feature_dir / "AutoGen"
    return {"view_base_h": auto / f"{screen['view_base']}.h", "view_base_cpp": auto / f"{screen['view_base']}.cpp",
            "widget_h": feature_dir / f"{screen['widget']}.h", "widget_cpp": feature_dir / f"{screen['widget']}.cpp"}


